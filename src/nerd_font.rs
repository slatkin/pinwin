    /// The three arrays keep the shape `unicode/lut.zig` requires: stage1
    /// covers every u21 page, stage3[0] is the shared `None`, and every
    /// stage2 index is in range for a page offset.
    #[test]
    fn table_shape_matches_lut() {
        assert_eq!(STAGE1.len(), 0x2000);
        assert_eq!(STAGE2.len(), 6400);
        assert_eq!(STAGE3.len(), 277);
        assert_eq!(STAGE3[0], None);
        assert!(STAGE2[..256].iter().all(|&v| v == 0));
        for &page in &STAGE1 {
            if page != 0 {
                assert!(
                    usize::from(page) + 255 < STAGE2.len(),
                    "stage1 page offset {page} out of range"
                );
            }
        }
        for &index in &STAGE2 {
            assert!(
                usize::from(index) < STAGE3.len(),
                "stage2 index {index} out of range"
            );
        }
    }

    /// `constraint` must return `None` on the shared empty page and otherwise
    /// agree with the direct stage2 composition, for every codepoint the
    /// stage1 tables describe.
    #[test]
    fn lookup_matches_table_for_all_pages() {
        for (high, &page) in STAGE1.iter().enumerate() {
            for low in 0..256usize {
                let cp = (high as u32) << 8 | low as u32;
                let got = constraint(cp);
                if page == 0 {
                    assert_eq!(got, None, "cp {cp:#x}");
                } else {
                    let want = STAGE3[STAGE2[page as usize + low] as usize];
                    assert_eq!(got, want, "cp {cp:#x}");
                }
            }
        }
    }
