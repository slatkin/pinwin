//! Nerd Font glyph constraints, ported from ghostty's generated
//! `src/font/nerd_font_tables.zig` (`Tables(?Constraint)`) at the pinned
//! commit 3a3047f6b62a791fd8b12d9f07a85b3d2160370b; the same source the C
//! `src/nerd_font_tables.h` was generated from, but at full f64 precision.
//!
//! It is a 3-level codepoint lookup identical in shape to ghostty's
//! `unicode/lut.zig`: `stage1` indexes a 256-entry page in `stage2`, whose
//! offset indexes `stage3`, and `stage3[0]` is the shared `None`. Pages with
//! no constrained glyph share the all-zero stage2 page 0, which `constraint`
//! returns `None` for after the stage1 load.
//!
//! Regenerate by re-running the extraction over the pinned source (the
//! stage1/stage2/stage3 arrays of `Tables(?Constraint)`), mapping the enum
//! literals to the Rust enums below, defaults for omitted fields, and
//! `max_xy_ratio = null` to `None`. Keep `constraint()` and the invariants
//! in the tests intact.

/// Sizing rule for a constrained glyph (`Constraint.Size`).
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Size {
    /// Don't change the size of this glyph.
    None,
    /// Scale down if needed to fit the bounds, preserving aspect ratio.
    Fit,
    /// Scale up or down to exactly match the bounds, preserving aspect ratio.
    Cover,
    /// Fit down, but scale up if the glyph doesn't cover one cell (Nerd Font rule).
    FitCover1,
    /// Stretch to exactly fit the bounds in both directions.
    Stretch,
}

/// Axis alignment rule (`Constraint.Align`).
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Align {
    /// Don't move the glyph on this axis.
    None,
    /// Align the leading (bottom/left) edge with the axis' leading edge.
    Start,
    /// Align the trailing (top/right) edge with the axis' trailing edge.
    End,
    /// Center on this axis.
    Center,
    /// Center, always with respect to the first cell (Nerd Font rule).
    Center1,
}

/// Height metric used when the constraint width is 1 (`Constraint.Height`).
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Height {
    /// The full line height of the primary face.
    Cell,
    /// The icon height from the grid metrics.
    Icon,
}

/// One Nerd Font glyph constraint (`Glyph.RenderOptions.Constraint`).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Constraint {
    pub size: Size,
    pub align_vertical: Align,
    pub align_horizontal: Align,
    pub pad_top: f64,
    pub pad_left: f64,
    pub pad_right: f64,
    pub pad_bottom: f64,
    pub relative_width: f64,
    pub relative_height: f64,
    pub relative_x: f64,
    pub relative_y: f64,
    /// Maximum width/height ratio when stretching; `None` is unset.
    pub max_xy_ratio: Option<f64>,
    pub max_constraint_width: u8,
    pub height: Height,
}

impl Constraint {
    /// The unconstrained value, matching ghostty's `Constraint.none`.
    pub const NONE: Constraint = Constraint {
        size: Size::None,
        align_vertical: Align::None,
        align_horizontal: Align::None,
        pad_top: 0.0,
        pad_left: 0.0,
        pad_right: 0.0,
        pad_bottom: 0.0,
        relative_width: 1.0,
        relative_height: 1.0,
        relative_x: 0.0,
        relative_y: 0.0,
        max_xy_ratio: None,
        max_constraint_width: 2,
        height: Height::Cell,
    };

    /// True when the constraint neither sizes nor positions the glyph
    /// (`Constraint.doesAnything`).
    pub fn does_anything(&self) -> bool {
        self.size != Size::None
            || self.align_horizontal != Align::None
            || self.align_vertical != Align::None
    }
}

