/// The Nerd Font constraint for `cp`, or `None` when it has none.
pub fn constraint(cp: u32) -> Option<Constraint> {
    if cp > 0x10FFFF {
        return None;
    }
    let low = (cp & 0xFF) as usize;
    let page = STAGE1[(cp >> 8) as usize];
    if page == 0 {
        return None;
    }
    STAGE3[STAGE2[page as usize + low] as usize]
}

